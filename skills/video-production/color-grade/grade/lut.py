def _hsv(r, g, b):
    mx = np.maximum(np.maximum(r, g), b)
    mn = np.minimum(np.minimum(r, g), b)
    df = mx - mn
    sat = np.divide(df, np.maximum(mx, 1e-8))
    hue = np.zeros_like(mx)
    safe = np.maximum(df, 1e-8)
    is_r = (mx == r) & (df > 0)
    is_g = (mx == g) & (df > 0) & ~is_r
    is_b = (df > 0) & ~is_r & ~is_g
    hue = np.where(is_r, np.mod((g - b) / safe, 6.0), hue)
    hue = np.where(is_g, (b - r) / safe + 2.0, hue)
    hue = np.where(is_b, (r - g) / safe + 4.0, hue)
    return np.mod(hue * 60.0, 360.0), sat, mx


def _ycbcr(r, g, b):
    y = 0.2126 * r + 0.7152 * g + 0.0722 * b
    return y, b - y, r - y


def _from_ycbcr(y, cb, cr):
    r = y + cr
    b = y + cb
    g = (y - 0.2126 * r - 0.0722 * b) / 0.7152
    return r, g, b


def _smooth(t):
    t = np.clip(t, 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def _soft(x):
    """Keep a little headroom so the legal-range stage, not the look, does the clip."""
    x = np.clip(x, -0.05, 1.15)
    over = np.maximum(x - 0.92, 0.0)
    under = np.minimum(x - 0.02, 0.0)
    y = x - over * over * 1.4 + under * under * 1.2
    return np.clip(y, 0.0, 1.0)


def apply_look(r, g, b, spec: dict):
    original = (r.copy(), g.copy(), b.copy())
    pivot = 0.45
    amount = spec["contrast"]
    r = pivot + (r - pivot) * amount
    g = pivot + (g - pivot) * amount
    b = pivot + (b - pivot) * amount
    y = 0.2126 * r + 0.7152 * g + 0.0722 * b
    sat = spec["saturation"]
    r = y + (r - y) * sat
    g = y + (g - y) * sat
    b = y + (b - y) * sat
    warm = spec["warmth"]
    r = r + warm
    b = b - warm * 0.8
    y2 = np.clip(0.2126 * r + 0.7152 * g + 0.0722 * b, 0.0, 1.0)
    weight = _smooth((y2 - 0.12) / 0.76)
    shadow = np.array(spec["shadow"], dtype=np.float32)
    highlight = np.array(spec["highlight"], dtype=np.float32)
    mix = shadow * (1.0 - weight)[..., None] + highlight * weight[..., None]
    r = r * mix[..., 0]
    g = g * mix[..., 1]
    b = b * mix[..., 2]
    hue, sat_in, val = _hsv(*original)
    skin = (
        (hue > 8.0)
        & (hue < 52.0)
        & (sat_in > 0.12)
        & (sat_in < 0.72)
        & (val > 0.22)
        & (val < 0.96)
    )
    protect = skin.astype(np.float32) * float(spec["skin"])
    y_g, cb_g, cr_g = _ycbcr(r, g, b)
    _y_o, cb_o, cr_o = _ycbcr(*original)
    cb = cb_g * (1.0 - protect) + cb_o * protect
    cr = cr_g * (1.0 - protect) + cr_o * protect
    r, g, b = _from_ycbcr(y_g, cb, cr)
    return _soft(r), _soft(g), _soft(b)


def generate_cube(spec: dict, size: int = 33) -> str:
    if size < 2 or size > 64:
        raise ValueError("LUT size must be between 2 and 64")
    grid = np.linspace(0.0, 1.0, size, dtype=np.float32)
    # Blue slowest, red fastest, which is the .cube order.
    bb, gg, rr = np.meshgrid(grid, grid, grid, indexing="ij")
    r, g, b = apply_look(rr, gg, bb, spec)
    flat_r = np.ravel(r, order="C")
    flat_g = np.ravel(g, order="C")
    flat_b = np.ravel(b, order="C")
    lines = [
        f'TITLE "{spec["title"]}"',
        "# Procedural house look. Generated by skills/video-production/color-grade.",
        "# Not derived from a copyrighted LUT.",
        f"LUT_3D_SIZE {size}",
        "DOMAIN_MIN 0.0 0.0 0.0",
        "DOMAIN_MAX 1.0 1.0 1.0",
    ]
    block = np.column_stack([flat_r, flat_g, flat_b])
    lines.extend(f"{row[0]:.6f} {row[1]:.6f} {row[2]:.6f}" for row in block)
    return "\n".join(lines) + "\n"


def write_looks(dest: Path, size: int = 33) -> list[Path]:
    dest.mkdir(parents=True, exist_ok=True)
    written = []
    for name, spec in LOOKS.items():
        path = dest / f"{name}.cube"
        path.write_text(generate_cube(spec, size))
        written.append(path)
    return written


def parse_cube(text: str) -> tuple[int, np.ndarray]:
    size = None
    rows = []
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or line.startswith("TITLE") or line.startswith("DOMAIN"):
            continue
        if line.startswith("LUT_3D_SIZE"):
            size = int(line.split()[-1])
            continue
        parts = line.split()
        if len(parts) == 3:
            rows.append([float(p) for p in parts])
    if size is None:
        raise ValueError("cube file has no LUT_3D_SIZE")
    table = np.asarray(rows, dtype=np.float32)
    if table.shape != (size ** 3, 3):
        raise ValueError(f"expected {size**3} rows, found {table.shape[0]}")
    return size, table
